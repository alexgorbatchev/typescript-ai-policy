export function isBaseUiPrimitiveExport(source: string, exportPath: readonly string[]): boolean {
  const name = exportPath.join(".");
  if (source === "@base-ui/react") {
    return [...NATIVE_EXPORTS.values()].some((names) => names.includes(name));
  }
  return NATIVE_EXPORTS.get(source)?.includes(name) ?? false;
}

export function readBaseUiEntryPath(source: string): string | null {
  if (source === "@base-ui/react") return "index";
  if (!NATIVE_EXPORTS.has(source)) return null;
  return source.slice("@base-ui/react/".length) + "/index";
}
